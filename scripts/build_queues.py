def norm(name: str) -> str:
    text = name.lower().replace("ё", "е").replace("ї", "и").replace("і", "и").replace("є", "е").replace("ґ", "г")
    for word in (
        "вулиця", "улица", "проспект", "просп.", "переулок", "провулок", "бульвар",
        "набережная", "площадь", "шоссе", "ул.", "пр.", "пер.",
    ):
        text = text.replace(word, " ")
    text = text.replace("’", "").replace("'", "").replace("-", "")
    return " ".join(text.split())


def street_names(blob: str) -> list[str]:
    found = []
    for match in re.finditer(r"(?:ул\.|пр\.|пер\.)\s*([^\d.]+)", blob, flags=re.I):
        name = " ".join(match.group(1).replace(",", " ").split())
        if name:
            found.append(name)
    return found


ALIASES = {
    "цитрусовая": "цитрусова",
    "засядько": "засядька",
    "листопрокатчиков": "листопрокатников",
    "цюрупы": "цюрупи",
    "аргуновых": "аргунових",
    "вершигоры": "вершигори",
    "глиера": "глиэра",
    "юрьева": "юрьева",
    "шафранная": "шафранна",
    "золотарева": "золотарьова",
    "трудовая аллея": "трудовой алеи",
    "королева": "королевой",
    "горбатова": "бориса горбатова",
    "богучаровский": "богучарский",
    "фиолетова": "ивана фиолетова",
    "студенческая": "студентская",
    "киселева": "кисельова",
}


def resolve(name: str, by_key: dict[str, str]) -> str | None:
    key = norm(name)
    if key in by_key:
        return by_key[key]
    alias = ALIASES.get(key)
    if alias and alias in by_key:
        return by_key[alias]
    contains = [osm for osm in by_key if key and (osm.endswith(key) or key.endswith(osm)) and abs(len(osm) - len(key)) <= 4]
    if len(contains) == 1:
        return by_key[contains[0]]
    return None


def main() -> None:
    index = json.loads(INDEX.read_text(encoding="utf-8"))
    by_key = {}
    for item in index:
        by_key.setdefault(norm(item["name"]), item["key"])
    blocks = []
    unmatched = []
    for blob in BLOCKS:
        keys = []
        for name in street_names(blob):
            key = resolve(name, by_key)
            if not key:
                unmatched.append(name)
                continue
            if key not in keys:
                keys.append(key)
        blocks.append(keys)
    OUT.write_text(
        json.dumps(
            {
                "anchor": "2026-10-09",
                "publishedUntil": "2026-10-16",
                "slots": [[6, 11], [11, 16], [16, 20], [20, 24]],
                "blocks": blocks,
                "unmatched": unmatched,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    print("blocks", [len(block) for block in blocks], "unmatched", unmatched)


if __name__ == "__main__":
    main()
